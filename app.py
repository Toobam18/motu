"""
MOTU web front end (Flask)
==========================

Run it:
    pip install flask networkx matplotlib
    python app.py            ->  open http://127.0.0.1:5000

Folder layout (put these next to script.py and USC.py):
    app.py
    static/index.html

This file only *serves* the graphs. Every graph is generated by script.py
(get_map / generate_random_graph / build_campus_graph / pick_start_goal);
nothing about the generator is re-implemented here. The searches come from
USC.py, astar.py and greedy.py (see ALGORITHMS below).
"""

import inspect
import math
import re
from pathlib import Path

import networkx as nx
from flask import Flask, jsonify, request, send_from_directory

from script import (COST_DISTRIBUTIONS, DISTANCE_BANDS, MAP_PRESETS, MAX_NODES,
                    MIN_NODES, build_campus_graph, describe_graph,
                    generate_random_graph, pick_start_goal)

# ---------------------------------------------------------------------------
# ALGORITHMS: each one is  fn(graph, start, goal) -> dict  with the keys
#     found, path, cost, nodes_expanded, time_ms, explored
# (same format as USC.py, astar.py and greedy.py).
# ---------------------------------------------------------------------------
from USC import ucs
from astar import a_star
from greedy import greedy

ALGORITHMS = {
    "ucs":    ucs,
    "astar":  a_star,
    "greedy": greedy,
}
ALGORITHM_NAMES = {
    "ucs":    "UCS",
    "astar":  "A*",
    "greedy": "Greedy",
}

STATIC_DIR = Path(__file__).parent / "static"
app = Flask(__name__, static_folder=None)

# Default knob values, read straight from generate_random_graph's signature so
# the UI can never drift from script.py.
DEFAULTS = {k: p.default
            for k, p in inspect.signature(generate_random_graph).parameters.items()
            if k != "seed"}
INT_KEYS = {"n_nodes", "size", "min_cost", "base_cost", "min_degree"}
FLOAT_KEYS = {"avg_degree", "cost_spread", "obstacle_density"}


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def _natural(name):
    """Sort N2 before N10."""
    m = re.match(r"(\D*)(\d*)$", name)
    return (m.group(1), int(m.group(2)) if m.group(2) else -1)


def _coerce(params):
    """Turn the JSON values coming from the browser into proper Python types."""
    out = {}
    for key, value in (params or {}).items():
        if key not in DEFAULTS:
            continue
        if key in INT_KEYS:
            value = int(float(value))
        elif key in FLOAT_KEYS:
            value = float(value)
        elif key == "keep_connected":
            value = value in (True, 1, "1", "true", "on")
        else:
            value = str(value)
        out[key] = value
    return out


def build_graph(spec):
    """Rebuild a graph from the browser's spec. Same seed = same graph, so the
    server never has to remember anything between requests."""
    preset = spec.get("preset", "medium")
    if preset not in MAP_PRESETS:
        raise ValueError(f"unknown map {preset!r}")
    if preset == "campus":
        return build_campus_graph()
    params = {**DEFAULTS, **MAP_PRESETS[preset], **_coerce(spec.get("params"))}
    seed = spec.get("seed")
    seed = None if seed in (None, "") else int(seed)
    return generate_random_graph(seed=seed, **params)


def graph_to_json(graph):
    pos = graph.graph.get("positions") or {n: graph.nodes[n]["pos"] for n in graph}
    weights = [d["weight"] for _, _, d in graph.edges(data=True)
               if d.get("weight") is not None]
    n, m = graph.number_of_nodes(), graph.number_of_edges()
    return {
        "name": graph.graph.get("name", "graph"),
        "seed": graph.graph.get("params", {}).get("seed"),
        "nodes": [{"id": v, "x": pos[v][0], "y": pos[v][1],
                   "indoor": bool(graph.nodes[v].get("indoor_option")),
                   "degree": graph.degree(v)}
                  for v in sorted(graph.nodes, key=_natural)],
        "edges": [{"u": u, "v": v, "weight": d.get("weight"),
                   "indoor": bool(d.get("indoor"))}
                  for u, v, d in graph.edges(data=True)],
        "blocked": [list(e) for e in graph.graph.get("blocked", [])],
        "summary": describe_graph(graph),
        "stats": {
            "nodes": n,
            "edges": m,
            "avg_degree": round(2 * m / n, 2) if n else 0,
            "cost_min": min(weights) if weights else None,
            "cost_max": max(weights) if weights else None,
            "cost_mean": round(sum(weights) / len(weights), 1) if weights else None,
            "blocked": len(graph.graph.get("blocked", [])),
            "components": nx.number_connected_components(graph),
        },
    }


def pick_pair(graph, band, seed=None):
    try:
        return pick_start_goal(graph, band=band, require_path=True, seed=seed)
    except ValueError:          # e.g. every edge blocked: no connected pair
        return None, None


def _clean(result):
    """Make a search result JSON-safe (sets -> lists, inf -> None)."""
    cost = result.get("cost")
    if isinstance(cost, float) and math.isinf(cost):
        cost = None
    return {
        "found": bool(result.get("found")),
        "path": list(result.get("path") or []),
        "cost": cost,
        "nodes_expanded": result.get("nodes_expanded"),
        "time_ms": result.get("time_ms"),
        "explored": sorted(result.get("explored") or [], key=_natural),
    }


def _error(msg, code=400):
    return jsonify({"error": msg}), code


# ---------------------------------------------------------------------------
# routes
# ---------------------------------------------------------------------------
@app.get("/")
def index():
    return send_from_directory(STATIC_DIR, "index.html")


@app.get("/api/config")
def config():
    presets = {name: (None if p is None else {**DEFAULTS, **p})
               for name, p in MAP_PRESETS.items()}
    return jsonify({
        "presets": presets,
        "cost_distributions": list(COST_DISTRIBUTIONS),
        "bands": list(DISTANCE_BANDS),
        "limits": {"min_nodes": MIN_NODES, "max_nodes": MAX_NODES},
        "algorithms": [{"id": k, "name": ALGORITHM_NAMES[k], "ready": fn is not None}
                       for k, fn in ALGORITHMS.items()],
    })


@app.post("/api/graph")
def api_graph():
    body = request.get_json(force=True) or {}
    try:
        graph = build_graph(body.get("spec", {}))
    except (ValueError, TypeError) as e:
        return _error(str(e))
    data = graph_to_json(graph)
    data["start"], data["goal"] = pick_pair(graph, body.get("band", "far"),
                                            body.get("pair_seed"))
    return jsonify(data)


@app.post("/api/pair")
def api_pair():
    body = request.get_json(force=True) or {}
    try:
        graph = build_graph(body.get("spec", {}))
    except (ValueError, TypeError) as e:
        return _error(str(e))
    start, goal = pick_pair(graph, body.get("band", "any"))
    return jsonify({"start": start, "goal": goal})


@app.post("/api/search")
def api_search():
    body = request.get_json(force=True) or {}
    try:
        graph = build_graph(body.get("spec", {}))
    except (ValueError, TypeError) as e:
        return _error(str(e))
    start, goal = body.get("start"), body.get("goal")
    if start not in graph or goal not in graph:
        return _error("pick a start and a goal that are on the map")

    results = []
    for algo in body.get("algorithms", []):
        if algo not in ALGORITHMS:
            continue
        row = {"id": algo, "name": ALGORITHM_NAMES[algo]}
        fn = ALGORITHMS[algo]
        if fn is None:
            row["status"] = "pending"
        else:
            try:
                row.update(status="ok", **_clean(fn(graph, start, goal)))
            except Exception as e:          # show the error on the card
                row.update(status="error", message=f"{type(e).__name__}: {e}")
        results.append(row)
    return jsonify({"results": results})


if __name__ == "__main__":
    app.run(debug=True)
